create extension if not exists pgcrypto;

create table if not exists public.amigos_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 40),
  birth_date date not null,
  city text not null default 'Machala',
  looking_for text not null check (looking_for in ('amistad','citas','ambos')),
  bio text default '' check (char_length(bio)<=300),
  interests text[] not null default '{}',
  photo_url text,
  active boolean not null default true,
  verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint amigos_adult_only check (birth_date <= (current_date - interval '18 years')::date)
);
alter table public.amigos_profiles add column if not exists updated_at timestamptz not null default now();

create table if not exists public.amigos_swipes (
  id bigint generated by default as identity primary key,
  from_user uuid not null references auth.users(id) on delete cascade,
  to_user uuid not null references auth.users(id) on delete cascade,
  decision text not null check (decision in ('like','pass')),
  created_at timestamptz not null default now(),
  unique(from_user,to_user), check(from_user<>to_user)
);
create table if not exists public.amigos_blocks (
  blocker uuid not null references auth.users(id) on delete cascade,
  blocked uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(blocker,blocked), check(blocker<>blocked)
);
create table if not exists public.amigos_reports (
  id bigint generated by default as identity primary key,
  reporter uuid not null references auth.users(id) on delete cascade,
  reported uuid not null references auth.users(id) on delete cascade,
  reason text not null,
  details text default '',
  status text not null default 'open' check(status in ('open','reviewed','closed')),
  created_at timestamptz not null default now()
);
create table if not exists public.amigos_date_proposals (
  id bigint generated by default as identity primary key,
  proposer uuid not null references auth.users(id) on delete cascade,
  invitee uuid not null references auth.users(id) on delete cascade,
  proposed_at timestamptz not null,
  message text default '' check(char_length(message)<=180),
  status text not null default 'pending' check(status in ('pending','accepted','declined','cancelled')),
  created_at timestamptz not null default now(),
  check(proposer<>invitee)
);
alter table public.amigos_date_proposals add column if not exists message text default '';

create table if not exists public.amigos_messages (
  id bigint generated by default as identity primary key,
  sender uuid not null references auth.users(id) on delete cascade,
  receiver uuid not null references auth.users(id) on delete cascade,
  body text not null check(char_length(body) between 1 and 600),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  check(sender<>receiver)
);
create index if not exists amigos_messages_parties_idx on public.amigos_messages(sender,receiver,created_at);
create index if not exists amigos_swipes_match_idx on public.amigos_swipes(from_user,to_user,decision);

