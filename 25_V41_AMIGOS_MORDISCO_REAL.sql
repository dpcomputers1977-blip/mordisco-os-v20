-- Directorio seguro: no expone correo, teléfono, fecha de nacimiento exacta ni user metadata.
create or replace function public.amigos_get_discovery(p_limit integer default 60)
returns table(user_id uuid,display_name text,age integer,city text,looking_for text,bio text,interests text[],photo_url text,verified boolean)
language sql stable security definer set search_path=public as $$
 select p.user_id,p.display_name,
        extract(year from age(current_date,p.birth_date))::integer as age,
        p.city,p.looking_for,p.bio,p.interests,p.photo_url,p.verified
 from amigos_profiles p
 where auth.uid() is not null
   and p.active=true and p.user_id<>auth.uid()
   and not exists(select 1 from amigos_blocks b where (b.blocker=auth.uid() and b.blocked=p.user_id) or (b.blocker=p.user_id and b.blocked=auth.uid()))
   and not exists(select 1 from amigos_swipes s where s.from_user=auth.uid() and s.to_user=p.user_id)
 order by p.created_at desc
 limit greatest(1,least(coalesce(p_limit,60),100));
$$;
revoke all on function public.amigos_get_discovery(integer) from public;
grant execute on function public.amigos_get_discovery(integer) to authenticated;

create or replace function public.amigos_get_matches()
returns table(user_id uuid,display_name text,age integer,city text,looking_for text,bio text,interests text[],photo_url text,verified boolean,matched_at timestamptz)
language sql stable security definer set search_path=public as $$
 select p.user_id,p.display_name,
        extract(year from age(current_date,p.birth_date))::integer as age,
        p.city,p.looking_for,p.bio,p.interests,p.photo_url,p.verified,
        greatest(a.created_at,b.created_at) as matched_at
 from amigos_swipes a
 join amigos_swipes b on b.from_user=a.to_user and b.to_user=a.from_user and b.decision='like'
 join amigos_profiles p on p.user_id=a.to_user and p.active=true
 where a.from_user=auth.uid() and a.decision='like'
   and not exists(select 1 from amigos_blocks bl where (bl.blocker=auth.uid() and bl.blocked=p.user_id) or (bl.blocker=p.user_id and bl.blocked=auth.uid()))
 order by greatest(a.created_at,b.created_at) desc;
$$;
revoke all on function public.amigos_get_matches() from public;
grant execute on function public.amigos_get_matches() to authenticated;

create or replace function public.amigos_get_messages(p_other_user uuid,p_limit integer default 120)
returns table(id bigint,sender uuid,receiver uuid,body text,created_at timestamptz,read_at timestamptz)
language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null or not public.amigos_is_match(auth.uid(),p_other_user) then raise exception 'No existe un Match activo'; end if;
 return query select m.id,m.sender,m.receiver,m.body,m.created_at,m.read_at from amigos_messages m
 where (m.sender=auth.uid() and m.receiver=p_other_user) or (m.sender=p_other_user and m.receiver=auth.uid())
 order by m.created_at asc limit greatest(1,least(coalesce(p_limit,120),300));
end $$;
revoke all on function public.amigos_get_messages(uuid,integer) from public;
grant execute on function public.amigos_get_messages(uuid,integer) to authenticated;

