-- Helpers: existe Match mutuo.
create or replace function public.amigos_is_match(a uuid,b uuid)
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from amigos_swipes x where x.from_user=a and x.to_user=b and x.decision='like')
    and exists(select 1 from amigos_swipes y where y.from_user=b and y.to_user=a and y.decision='like')
    and not exists(select 1 from amigos_blocks z where (z.blocker=a and z.blocked=b) or (z.blocker=b and z.blocked=a));
$$;
revoke all on function public.amigos_is_match(uuid,uuid) from public;
grant execute on function public.amigos_is_match(uuid,uuid) to authenticated;

